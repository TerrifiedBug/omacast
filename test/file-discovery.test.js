const test = require("node:test")
const assert = require("node:assert/strict")
const { mkdtemp, mkdir, writeFile, symlink, rm } = require("node:fs/promises")
const { tmpdir } = require("node:os")
const path = require("node:path")
const { spawnSync } = require("node:child_process")
const Model = require("../Model.js")

test("file discovery never traverses a symlink out of the selected tree", async t => {
  const dir = await mkdtemp(path.join(tmpdir(), "omacast-discovery-links-"))
  t.after(() => rm(dir, { recursive: true, force: true }))
  const root = path.join(dir, "selected")
  const outside = path.join(dir, "outside")
  await mkdir(root)
  await mkdir(outside)
  const expected = path.join(root, "normal-needle.txt")
  await writeFile(expected, "local")
  await writeFile(path.join(outside, "outside-needle.txt"), "outside")
  await symlink(outside, path.join(root, "bridge"), "dir")
  const argv = Model.fileCommand(root, ["needle"], "all")
  const result = spawnSync(argv[0], argv.slice(1), { encoding: "utf8", timeout: 7000 })
  assert.equal(result.status, 0, result.stderr)
  assert.deepEqual(Model.parseFilePaths(result.stdout), [expected])
})
